#!/bin/bash
# "Bring your own N9 files": builds the "N9 icons" icon pack (ADW/Nova appfilter format) from
# the N9 app icons that import.sh copied into vendor/harmattan-n9/app-icons, using
# iconpack/mapping.txt. The result goes to vendor/harmattan-n9/iconpack, which the build picks
# up as N9IconPack only if it exists. Nokia's icons are never part of this repository or of
# published builds; each developer supplies them from their own N9.
#
#   make-iconpack.sh [icons-dir]    (default: vendor/harmattan-n9/app-icons)
set -e
HERE="$(cd "$(dirname "$0")" && pwd)"
DEST="$(cd "$HERE/../.." && pwd)/harmattan-n9"
ICONS="${1:-$DEST/app-icons}"
OUT="$DEST/iconpack"
rm -rf "$OUT"; mkdir -p "$OUT/res/xml" "$OUT/res/drawable-nodpi"

cat > "$OUT/AndroidManifest.xml" <<'XML'
<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by vendor/etesian/n9-files/make-iconpack.sh from the user's own N9 icons. -->
<manifest xmlns:android="http://schemas.android.com/apk/res/android"
    package="com.bompotis.etesian.iconpack.n9">
    <application android:label="N9 icons" android:hasCode="false">
        <activity android:name="android.app.Activity" android:exported="true"
            android:theme="@android:style/Theme.NoDisplay">
            <intent-filter>
                <action android:name="org.adw.launcher.THEMES" />
                <category android:name="android.intent.category.DEFAULT" />
            </intent-filter>
            <intent-filter>
                <action android:name="com.novalauncher.THEME" />
                <category android:name="android.intent.category.DEFAULT" />
            </intent-filter>
        </activity>
    </application>
</manifest>
XML

{ echo '<?xml version="1.0" encoding="utf-8"?>'
  echo '<resources>'
  grep -v '^\s*\(#\|$\)' "$HERE/iconpack/mapping.txt" | while read -r comp icon; do
      [ -f "$ICONS/$icon.png" ] || continue
      # Resource names allow only [a-z0-9_].
      name=$(echo "$icon" | tr 'A-Z-' 'a-z_' | tr -cd 'a-z0-9_')
      cp "$ICONS/$icon.png" "$OUT/res/drawable-nodpi/$name.png"
      echo "    <item component=\"ComponentInfo{$comp}\" drawable=\"$name\" />"
  done
  echo '</resources>'; } > "$OUT/res/xml/appfilter.xml"
echo "Made the N9 icon pack in $OUT ($(ls "$OUT/res/drawable-nodpi" | wc -l) icons)"
