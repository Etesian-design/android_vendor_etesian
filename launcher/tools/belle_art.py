#!/usr/bin/env python3
"""Generates the Belle Classic widget drawables (res/drawable/bc_*.xml) from the measurements of the Nokia 701's own widget art
(decoded .nvg files, reference only; nothing of it ships). The same numbers as the Storybook (etesian-design
src/stories/belle/BelleDial.vue, BelleCap.vue, BelleOnOff.vue):

  - every face is a squircle stretched to its box, never a rounded rectangle: n 2.9 for the dial, 2.95 for the toggle caps,
    3.6 for the on/off track, 2.7 for its knob and the data meter
  - the dial (a 126 grid): warm charcoal #41413C -> #282823 in a #50504B -> #34342F bezel, white bars at 12/3/6/9, faint ticks
    between, a date window at 3 o'clock; white hour (0.60 r, 5 wide) and minute (0.86 r, 2.6 wide) hands, #4791DC second hand
  - the toggle cap (72 x 82): blue-grey metal #A6B6C1 -> #555E70, up over a blue well when on, down in a dark well when off
  - the on/off switch (66 x 44): green #7EC142 -> #1C6332 or grey track, white knob with the power glyph, left when on

Run: python3 tools/belle_art.py   (from launcher/; rewrites the files listed in OUT)
"""
import math, os

RES = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'app', 'src', 'main', 'res', 'drawable')
HEAD = '<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by tools/belle_art.py from the 701 measurements; edit the script, not this file. -->\n'


def squircle(w, h, n, x=0.0, y=0.0, samples=96):
    pts = []
    for i in range(samples):
        t = i / samples * 2 * math.pi
        c, s = math.cos(t), math.sin(t)
        px = x + w / 2 + w / 2 * math.copysign(abs(c) ** (2 / n), c)
        py = y + h / 2 + h / 2 * math.copysign(abs(s) ** (2 / n), s)
        pts.append(f'{px:.2f},{py:.2f}')
    return 'M' + 'L'.join(pts) + 'Z'


def grad(stops, y1, y2):
    items = ''.join(f'<item android:offset="{o}" android:color="{c}"/>' for o, c in stops)
    return (f'<aapt:attr name="android:fillColor"><gradient android:type="linear" android:startX="0" android:startY="{y1}" '
            f'android:endX="0" android:endY="{y2}">{items}</gradient></aapt:attr>')


def path(d, fill=None, gradient=None, stroke=None, width=None, extra=''):
    a = f'android:pathData="{d}"'
    if fill: a += f' android:fillColor="{fill}"'
    if stroke: a += f' android:strokeColor="{stroke}" android:strokeWidth="{width}"'
    if extra: a += ' ' + extra
    return f'    <path {a}>{gradient}</path>\n' if gradient else f'    <path {a}/>\n'


def vector(w, h, vw, vh, body):
    return (HEAD + f'<vector xmlns:android="http://schemas.android.com/apk/res/android" xmlns:aapt="http://schemas.android.com/aapt"\n'
            f'    android:width="{w}dp" android:height="{h}dp" android:viewportWidth="{vw}" android:viewportHeight="{vh}">\n{body}</vector>\n')


def rot(x1, y1, x2, y2, deg, c=63):
    r = math.radians(deg)
    f = lambda x, y: (c + (x - c) * math.cos(r) - (y - c) * math.sin(r), c + (x - c) * math.sin(r) + (y - c) * math.cos(r))
    (a, b), (p, q) = f(x1, y1), f(x2, y2)
    return f'M{a:.2f},{b:.2f}L{p:.2f},{q:.2f}'


OUT = {}

# ---- the dial: 400dp so AnalogClock (which only scales down) fills any widget; hands share the size and grid ----
dial = path(squircle(126, 126, 2.9), gradient=grad([(0, '#FF5A5A55'), (0.5, '#FF3E3E39'), (1, '#FF34342F')], 0, 126), stroke='#FF1C1C19', width=1)
dial += path(squircle(118, 118, 2.9, 4, 4), gradient=grad([(0, '#FF41413C'), (0.22, '#FF373732'), (0.59, '#FF32322D'), (1, '#FF282823')], 4, 122))
dial += path(squircle(118, 118, 2.9, 4, 4), stroke='#21FFFFFF', width=0.8)
dial += path(''.join(rot(63, 10.5, 63, 15.3, a) for a in (0, 90, 180, 270)), stroke='#FFFFFFFF', width=2.7, extra='android:strokeLineCap="round"')
dial += path(''.join(rot(63, 11.5, 63, 15.5, a) for a in (30, 60, 120, 150, 210, 240, 300, 330)), stroke='#66D6D6D6', width=1.6, extra='android:strokeLineCap="round"')
OUT['bc_square_dial'] = vector(400, 400, 126, 126, dial)

# the date window at 3 o'clock (26 of 126); BelleClassic2.SQUIRCLE places and sizes it
OUT['bc_date_box'] = vector(26, 26, 26, 26, path(squircle(26, 26, 2.8), gradient=grad([(0, '#FF2A2A26'), (1, '#FF3C3C37')], 0, 26), stroke='#59000000', width=0.8))

# hands: a darker outline stands in for the shadow (vectors cannot blur); the hub rides on the minute hand
OUT['bc_hand_hour_l'] = vector(400, 400, 126, 126, path('M60.5,68L60.6,25.5Q63,24.2 65.4,25.5L65.5,68Z', fill='#FFFFFFFF', stroke='#40000000', width=0.6))
OUT['bc_hand_minute_l'] = vector(400, 400, 126, 126,
    path('M61.7,68L61.75,9.4Q63,8.6 64.25,9.4L64.3,68Z', fill='#FFFFFFFF', stroke='#40000000', width=0.6)
    + path('M63,58a5,5 0,1 1,0 10a5,5 0,1 1,0 -10z', fill='#FFFFFFFF', stroke='#40000000', width=0.6)
    + path('M63,60.8a2.2,2.2 0,1 1,0 4.4a2.2,2.2 0,1 1,0 -4.4z', fill='#FF4791DC')
    + path('M63,62a1,1 0,1 1,0 2a1,1 0,1 1,0 -2z', fill='#FFFFFFFF'))
OUT['bc_hand_second'] = vector(400, 400, 126, 126,
    path('M63,84V9', stroke='#FF4791DC', width=1.1)
    + path('M63,60.8a2.2,2.2 0,1 1,0 4.4a2.2,2.2 0,1 1,0 -4.4z', fill='#FF4791DC')
    + path('M63,62a1,1 0,1 1,0 2a1,1 0,1 1,0 -2z', fill='#FFFFFFFF'))

# ---- the toggle cap (switches 4x1 and the 1x1 switch) ----
def cap(on):
    metal = lambda y1, y2: grad([(0, '#FFA6B6C1'), (1, '#FF555E70')], y1, y2)
    body = path(squircle(72, 82, 2.95), gradient=metal(0, 82), stroke='#4D010101', width=1)
    if on:
        body += path(squircle(66, 76, 2.95, 3, 3), gradient=grad([(0, '#FF2FA7DD'), (0.16, '#FF2F86DD'), (1, '#FF355CA6')], 3, 79), stroke='#FF355CA6', width=0.8)
    else:
        body += path(squircle(66, 76, 2.95, 3, 3), fill='#FF4E5662', stroke='#FF808C9A', width=0.8)
    y = 4 if on else 14
    body += path(squircle(64, 64, 2.95, 4, y), gradient=metal(y, y + 64), stroke='#4D010101', width=1)
    body += path(squircle(64, 64, 2.95, 4, y), gradient=grad([(0, '#40FFFFFF'), (1, '#00FFFFFF')], y, y + 64))
    return vector(72, 82, 72, 82, body)
OUT['bc_toggle_on'] = OUT['bc_sw_on'] = cap(True)
OUT['bc_toggle_off'] = OUT['bc_sw_off'] = cap(False)

# ---- the on/off switch (FM radio, Wi-Fi 2x1) ----
POWER = 'M11,3h2v9h-2zM7.05,5.64l1.41,1.42A6,6 0,1 0,15.54 7l1.41,-1.41A8,8 0,1 1,7.05 5.64z'
def onoff(on):
    body = path(squircle(64, 42, 3.6, 1, 1), gradient=grad([(0, '#FF7EC142' if on else '#FFADADAD'), (1, '#FF1C6332' if on else '#FF464646')], 1, 43), stroke='#A8FFFFFF', width=1.2)
    kx = 3 if on else 25
    body += path(squircle(38, 38, 2.7, kx, 3), gradient=grad([(0, '#FFFFFFFF'), (1, '#FF808081')], 3, 41), stroke='#33000000', width=1)
    glyph = path(POWER, gradient=grad([(0, '#FF37B24A' if on else '#FFBBBDBF'), (1, '#FF006838' if on else '#FF7A7C7F')], 3, 21))
    body += f'    <group android:translateX="{kx + 7}" android:translateY="10">\n    {glyph}    </group>\n'
    return vector(66, 44, 66, 44, body)
OUT['bc_power_on'] = onoff(True)
OUT['bc_power_off'] = onoff(False)

for name, xml in OUT.items():
    with open(os.path.join(RES, name + '.xml'), 'w') as f:
        f.write(xml)
print('wrote', len(OUT), 'drawables')
